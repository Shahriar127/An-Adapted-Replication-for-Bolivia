"""
make_tables.py — build every manuscript table directly from the FINAL result files.

Read-only: no model is fitted. Writes one CSV per table plus TABLES.md into
final_manuscript/tables/. Run from anywhere:  python3 final_manuscript/tables/make_tables.py

Published values (McBride & Nichols 2018) are typed in from the article, as
printed (percent), and converted to proportions; they are labelled 'published'.
"""
import os

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
R = lambda *p: os.path.join(ROOT, *p)  # noqa: E731
BASE = "189.09 (full-sample P24.2)"
M = ["TA", "PA", "UC", "LE", "BPAC"]
md = ["# Manuscript tables (generated)\n",
      "Generated by `final_manuscript/tables/make_tables.py` from the FINAL result files. "
      "Do not edit by hand; re-run the script.\n"]


def emit(name, title, df, source, note=""):
    df.to_csv(os.path.join(HERE, f"{name}.csv"), index=False)
    md.append(f"\n## {title}\n\n*File:* `{name}.csv` · *Source:* {source}\n")
    if note:
        md.append(f"\n{note}\n")
    md.append("\n" + df.to_markdown(index=False) + "\n")


def fmt_ci(m, lo, hi):
    return f"{m:.3f} [{lo:.3f}, {hi:.3f}]"


# ── Table 1: replication vs published Table A1 (published protocol, seed 42) ──
p = pd.read_csv(R("results/sensitivity/primary_metrics_bootstrap_ci.csv"))
p = p[(p.protocol == "paper") & (p.threshold == BASE)].set_index("model")
cv = pd.read_csv(R("results/cv_qr/cv_qr_results.csv"))
cv = cv[(cv.protocol == "paper") & (cv.line == "base")].iloc[0]
pub = {  # Table A1, pp. 545-546 (percent): TA, PA, UC, LE, BPAC, BPAC_lo, BPAC_hi
    "IRIS QR(0.42)": ("QR(0.42), row 2", 81.88, 57.58, 42.42, 34.30, 49.33, 36.73, 60.48),
    "CV-QR": ("CV QR(0.38)", 81.76, 63.37, 36.63, 41.61, 57.94, 50.61, 63.44),
    "SE": ("SE QRF(0.41)", 80.17, 55.33, 44.67, 40.44, 50.18, 39.26, 58.57),
}
se_lab = [k for k in p.index if k.startswith("SE OOB-selected")][0]
rows = []
for lab, src, pk in (("IRIS QR(0.42)", p.loc["IRIS_Q42"], "IRIS QR(0.42)"),
                     (f"CV-QR, selected q = {cv.q:.2f}", cv, "CV-QR"),
                     (f"SE, selected {se_lab.split('(', 1)[1][:-1]}", p.loc[se_lab], "SE"),
                     ("RF (conditional mean)", p.loc["RandomForest"], None),
                     ("Decision tree (reference)", p.loc["DecisionTree"], None)):
    r = {"model": lab, **{m: round(float(src[m]), 3) for m in M},
         "BPAC_95CI": f"[{src['BPAC_lo']:.3f}, {src['BPAC_hi']:.3f}]"}
    if pk:
        v = pub[pk]
        r.update(published_model=v[0], **{f"pub_{m}": round(x / 100, 3) for m, x in zip(M, v[1:6])},
                 pub_BPAC_95CI=f"[{v[6] / 100:.3f}, {v[7] / 100:.3f}]")
    rows.append(r)
emit("table1_replication", "Table 1. Replication against published Table A1 (published protocol, seed 42)",
     pd.DataFrame(rows).fillna(""),
     "`results/sensitivity/primary_metrics_bootstrap_ci.csv`, `results/cv_qr/cv_qr_results.csv`, published Table A1",
     "Test-sample bootstrap means (1,000 resamples) with 95% percentile CI.")

# ── Table 2: validation protocol, 30 splits ─────────────────────────────────
r = pd.read_csv(R("results/sensitivity/repeated_splits_raw.csv"))
rb = r[r.threshold == BASE]
order = [("SE OOB-selected", "SE (OOB-selected QRF)"), ("QRF(q=0.40) fixed", "QRF(0.40) fixed"),
         ("QRF(q=0.45) fixed", "QRF(0.45) fixed"), ("IRIS_Q42", "IRIS QR(0.42)"),
         ("RandomForest", "RF (conditional mean)")]
rows = []
for k, lab in order:
    g = rb[rb.model == k].groupby("protocol").BPAC
    mu, sd = g.mean(), g.std()
    rows.append(dict(model=lab, published_mean=round(mu["paper"], 3), published_sd=round(sd["paper"], 3),
                     disjoint_mean=round(mu["disjoint"], 3), disjoint_sd=round(sd["disjoint"], 3),
                     difference=round(mu["disjoint"] - mu["paper"], 3)))
emit("table2_validation_protocol", "Table 2. BPAC by validation protocol, 30 splits per protocol (seeds 1000–1029)",
     pd.DataFrame(rows), "`results/sensitivity/repeated_splits_raw.csv`",
     "Mean (SD) of point estimates on the full test sample; difference = disjoint − published.")

# ── Table 3: A8 one-factor audit (20 splits) ────────────────────────────────
a = pd.read_csv(R("results/a8_audit/a8_summary.csv"))
a = a[a.model == "SE"][["config", "BPAC_mean", "BPAC_std", "dBPAC_vs_B0", "gap_in_SDs"]]
emit("table3_a8_audit", "Table 3. A8 implementation audit: SE BPAC by configuration (published protocol, 20 splits)",
     a.round(3), "`results/a8_audit/a8_summary.csv`",
     "Published SE BPAC = 0.502. `gap_in_SDs` = (ours − published) / across-split SD. "
     "Across all configurations and the SE, QRF(0.40) and QRF(0.41) rows the gap is "
     f"{pd.read_csv(R('results/a8_audit/a8_summary.csv')).gap_in_SDs.min():.1f}–"
     f"{pd.read_csv(R('results/a8_audit/a8_summary.csv')).gap_in_SDs.max():.1f} SDs.")

# ── In-text table §5.4: reconstructed thresholds (30 splits) ────────────────
rows = []
for pr in ("disjoint", "paper"):
    base = r[(r.protocol == pr) & (r.threshold == BASE)].set_index(["seed", "model"]).BPAC
    for th in [t for t in r.threshold.unique() if t != BASE]:
        d = (r[(r.protocol == pr) & (r.threshold == th)].set_index(["seed", "model"]).BPAC - base)
        for k, lab in (("SE OOB-selected", "SE (OOB)"), ("QRF(q=0.40) fixed", "QRF(0.40)"),
                       ("IRIS_Q42", "IRIS QR(0.42)"), ("RandomForest", "RF")):
            dd = d.xs(k, level="model")
            rows.append(dict(protocol=pr, threshold=th, model=lab,
                             mean_change=round(dd.mean(), 3), sd=round(dd.std(), 3)))
t = pd.DataFrame(rows).pivot_table(index=["protocol", "model"], columns="threshold",
                                   values="mean_change", sort=False).reset_index()
emit("tableS1_threshold_sensitivity", "Table S1 (section IV.4). Mean change in BPAC vs 189.09 Bs, 30 splits",
     t.round(3), "`results/sensitivity/repeated_splits_raw.csv`")

# ── In-text table §5.5: metric definition (correction C1) ───────────────────
c = pd.read_csv(R("results/audit/correction_impact.csv"))
rows = []
for pr in ("paper", "disjoint"):
    for mod, met in (("IRIS QR(0.42)", "BPAC"), ("IRIS QR(0.42)", "PA"), ("QRF(0.40) fixed", "BPAC")):
        g = c[(c.protocol == pr) & (c.model == mod)].set_index("step")[met]
        rows.append(dict(protocol=pr, model=mod, metric=met, working_paper_TPplusFP=g["0 pre-freeze"],
                         published_TPplusFN=g["1 +C1 metrics"]))
emit("tableS2_metric_definition", "Table S2 (section IV.5). 2015 working-paper formula vs published definition",
     pd.DataFrame(rows).round(3), "`results/audit/correction_impact.csv`")

# ── In-text table §5.6: paired contrasts, seed 42 ───────────────────────────
pc = pd.read_csv(R("results/cv_qr/paired_comparisons.csv"))
pc = pc[pc.metric == "BPAC"]
rows = []
for con in ("CV - IRIS", "SE - IRIS", "CV - SE"):
    rr = {"contrast": con.replace("CV", "CV-QR")}
    for pr in ("paper", "disjoint"):
        x = pc[(pc.protocol == pr) & (pc.contrast == con)].iloc[0]
        rr[f"{pr}"] = f"{x['diff']:+.3f} [{x.lo:+.3f}, {x.hi:+.3f}]"
    rr["published_table4_pp"] = pc[pc.contrast == con].published_table4.iloc[0]
    rows.append(rr)
emit("tableS3_paired_contrasts", "Table S3 (section IV.6). Paired BPAC contrasts on identical test households (seed 42)",
     pd.DataFrame(rows), "`results/cv_qr/paired_comparisons.csv`",
     "Mean difference [95% paired test-bootstrap CI]. Published Table 4 in percentage points (* = significant at 1% in the paper).")

# ── In-text table §5.6: 3-split pilot ───────────────────────────────────────
pl = pd.read_csv(R("audit_2026-11-04_repeated_split/outputs/pilot_per_split_results.csv"))
pl = pl[pl.line == "P24.2_frozen"]
pl = pd.DataFrame(dict(seed=pl.seed, cvqr_q=pl.cvqr_q, BPAC_cvqr=pl.BPAC_cvqr.round(3),
                       qrf_selected=pl.qrf_selected, BPAC_qrf=pl.BPAC_qrf.round(3),
                       delta_cvqr_minus_qrf=pl.dBPAC_cvqr_minus_qrf.round(3),
                       CI95=[f"[{a:+.3f}, {b:+.3f}]" for a, b in zip(pl.dBPAC_boot_lo, pl.dBPAC_boot_hi)]))
emit("tableS4_pilot_cvqr_vs_qrf", "Table S4 (section IV.6). Three-split pilot, CV-QR vs QRF (published protocol)",
     pl, "`audit_2026-11-04_repeated_split/outputs/pilot_per_split_results.csv`",
     "Pilot only (n = 3); descriptive, not inferential.")

# ── In-text §5.4: Table A2 analogue ─────────────────────────────────────────
ta = pd.read_csv(R("results/table_a2/table_a2_results.csv"))
ta = ta[ta.protocol == "paper"][["line", "line_value", "poverty_rate_full", "model", "BPAC", "BPAC_lo", "BPAC_hi"]]
emit("tableS5_halved_doubled_lines", "Table S5 (section IV.4). Halved and doubled lines (Table A2 analogue, published protocol, seed 42)",
     ta.round(3), "`results/table_a2/table_a2_results.csv`; published values in `results/table_a2/table_a2_published_bolivia.csv`")

# ── Dataset description ─────────────────────────────────────────────────────
ds = pd.read_csv(R("results/dataset/descriptive_statistics.csv"))
emit("tableS6_descriptive_statistics", "Table S6. Descriptive statistics of the analysis sample (N = 4,086)",
     ds.drop(columns=["n_missing"]).round(3), "`results/dataset/descriptive_statistics.csv` (from `describe_dataset.py`)")

open(os.path.join(HERE, "TABLES.md"), "w").write("".join(md))
print(f"tables written to {HERE}")
